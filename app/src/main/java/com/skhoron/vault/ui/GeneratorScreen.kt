private enum class GeneratorMode { PASSWORD, PASSPHRASE, PIN }

/**
 * suggestedLabel — передаётся извне (из AutofillService: домен страницы или имя
 * пакета приложения). Юзер может отредактировать перед сохранением.
 */
@Composable
fun GeneratorScreen(
    suggestedLabel: String? = null,
    onSave: (label: String, username: String?, password: String) -> Unit,
    onCancel: () -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val generator = remember { PasswordGenerator() }
    val wordList = remember { WordList.load(context) }

    var mode by remember { mutableStateOf(GeneratorMode.PASSWORD) }
    var options by remember { mutableStateOf(GeneratorOptions()) }
    var wordCount by remember { mutableStateOf(6) }
    var pinLength by remember { mutableStateOf(6) }
    var label by remember { mutableStateOf(suggestedLabel ?: "") }
    var username by remember { mutableStateOf("") }

    fun create(): GeneratedPassword = when (mode) {
        GeneratorMode.PASSWORD -> generator.generate(options)
        GeneratorMode.PASSPHRASE -> generator.generatePassphrase(wordList, wordCount)
        GeneratorMode.PIN -> generator.generatePin(pinLength)
    }

    var generated by remember { mutableStateOf(create()) }

    fun regenerate() {
        generated = create()
    }

    /** Нельзя снять последний выбранный класс символов. */
    fun toggleClasses(new: GeneratorOptions) {
        if (new.useLower || new.useUpper || new.useDigits || new.useSymbols) {
            options = new
            regenerate()
        }
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(24.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Text(
            stringResource(R.string.generate_password),
            fontSize = 22.sp,
            fontWeight = FontWeight.SemiBold
        )
        Spacer(Modifier.height(16.dp))

        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            FilterChip(
                selected = mode == GeneratorMode.PASSWORD,
                onClick = { mode = GeneratorMode.PASSWORD; regenerate() },
                label = { Text("Пароль") }
            )
            if (wordList.isNotEmpty()) {
                FilterChip(
                    selected = mode == GeneratorMode.PASSPHRASE,
                    onClick = { mode = GeneratorMode.PASSPHRASE; regenerate() },
                    label = { Text("Фраза") }
                )
            }
            FilterChip(
                selected = mode == GeneratorMode.PIN,
                onClick = { mode = GeneratorMode.PIN; regenerate() },
                label = { Text("PIN") }
            )
        }

        Spacer(Modifier.height(16.dp))
        PasswordDisplay(generated)

        Spacer(Modifier.height(16.dp))
        Text(
            text = stringResource(R.string.entropy_label, generated.entropyBits.toInt()),
            color = SkhoronAccent,
            fontSize = 14.sp
        )

        Spacer(Modifier.height(24.dp))
        when (mode) {
            GeneratorMode.PASSWORD -> {
                Text(stringResource(R.string.password_length), fontSize = 13.sp, color = SkhoronTextDim)
                Slider(
                    value = options.length.toFloat(),
                    onValueChange = {
                        options = options.copy(length = it.toInt())
                        regenerate()
                    },
                    valueRange = PasswordGenerator.MIN_LENGTH.toFloat()..PasswordGenerator.MAX_LENGTH.toFloat()
                )
                Text("${options.length} символов", fontSize = 12.sp, color = SkhoronTextDim)

                Spacer(Modifier.height(8.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    FilterChip(
                        selected = options.useLower,
                        onClick = { toggleClasses(options.copy(useLower = !options.useLower)) },
                        label = { Text("a-z") }
                    )
                    FilterChip(
                        selected = options.useUpper,
                        onClick = { toggleClasses(options.copy(useUpper = !options.useUpper)) },
                        label = { Text("A-Z") }
                    )
                    FilterChip(
                        selected = options.useDigits,
                        onClick = { toggleClasses(options.copy(useDigits = !options.useDigits)) },
                        label = { Text("0-9") }
                    )
                    FilterChip(
                        selected = options.useSymbols,
                        onClick = { toggleClasses(options.copy(useSymbols = !options.useSymbols)) },
                        label = { Text("!@#") }
                    )
                }
                Spacer(Modifier.height(8.dp))
                FilterChip(
                    selected = options.excludeAmbiguous,
                    onClick = {
                        options = options.copy(excludeAmbiguous = !options.excludeAmbiguous)
                        regenerate()
                    },
                    label = { Text("Без похожих символов (Il1 O0)") }
                )
            }

            GeneratorMode.PASSPHRASE -> {
                Text("Слов в фразе", fontSize = 13.sp, color = SkhoronTextDim)
                Slider(
                    value = wordCount.toFloat(),
                    onValueChange = {
                        wordCount = it.toInt()
                        regenerate()
                    },
                    valueRange = PasswordGenerator.MIN_WORDS.toFloat()..PasswordGenerator.MAX_WORDS.toFloat(),
                    steps = PasswordGenerator.MAX_WORDS - PasswordGenerator.MIN_WORDS - 1
                )
                Text("$wordCount слов", fontSize = 12.sp, color = SkhoronTextDim)
            }

            GeneratorMode.PIN -> {
                Text("Длина PIN", fontSize = 13.sp, color = SkhoronTextDim)
                Slider(
                    value = pinLength.toFloat(),
                    onValueChange = {
                        pinLength = it.toInt()
                        regenerate()
                    },
                    valueRange = PasswordGenerator.MIN_PIN.toFloat()..PasswordGenerator.MAX_PIN.toFloat(),
                    steps = PasswordGenerator.MAX_PIN - PasswordGenerator.MIN_PIN - 1
                )
                Text("$pinLength цифр", fontSize = 12.sp, color = SkhoronTextDim)
            }
        }

        Spacer(Modifier.height(8.dp))
        Button(onClick = { regenerate() }, modifier = Modifier.fillMaxWidth()) {
            Text("Сгенерировать заново")
        }

        Spacer(Modifier.height(24.dp))
        Divider()
        Spacer(Modifier.height(16.dp))

        OutlinedTextField(
            value = label,
            onValueChange = { label = it },
            label = { Text(stringResource(R.string.label_hint)) },
            singleLine = true,
            modifier = Modifier.fillMaxWidth()
        )
        Spacer(Modifier.height(12.dp))
        OutlinedTextField(
            value = username,
            onValueChange = { username = it },
            label = { Text(stringResource(R.string.username_hint)) },
            singleLine = true,
            modifier = Modifier.fillMaxWidth()
        )

        Spacer(Modifier.height(20.dp))
        Row(modifier = Modifier.fillMaxWidth()) {
            OutlinedButton(onClick = onCancel, modifier = Modifier.weight(1f)) {
                Text(stringResource(R.string.cancel))
            }
            Spacer(Modifier.width(12.dp))
            Button(
                onClick = {
                    onSave(
                        label.ifBlank { suggestedLabel ?: "Без названия" },
                        username.ifBlank { null },
                        generated.value
                    )
                },
                enabled = label.isNotBlank() || suggestedLabel != null,
                modifier = Modifier.weight(1f)
            ) {
                Text(stringResource(R.string.save))
            }
        }
    }
}

@Composable
private fun PasswordDisplay(generated: GeneratedPassword) {
    Card(modifier = Modifier.fillMaxWidth()) {
        Text(
            text = generated.value,
            fontFamily = FontFamily.Monospace,
            fontSize = 13.sp,
            modifier = Modifier.padding(16.dp)
        )
    }
}